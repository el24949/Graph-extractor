"""Measure pipeline accuracy on the synthetic charts in samples/.

This is the only module allowed to read *_meta.json: it uses the axis limits
there as the calibration values, then compares the output to *_truth.csv.

Run from the project root:
    python -m src.evaluate
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.pipeline import extract_series

ROOT = Path(__file__).resolve().parent.parent
SAMPLES_DIR = ROOT / "samples"
OUT_PATH = ROOT / "docs" / "extraction_results.md"


def evaluate_chart(img_path):
    """Run the pipeline on one chart and return (mode, rmse_pct, mae_pct).

    Errors are relative to the y-range (ymax - ymin) from the meta file.
    """
    meta = json.loads(img_path.with_name(f"{img_path.stem}_meta.json").read_text())
    truth = pd.read_csv(img_path.with_name(f"{img_path.stem}_truth.csv"))

    df, mode, _, _ = extract_series(
        img_path,
        x_ref=(meta["xmin"], meta["xmax"]),
        y_ref=(meta["ymin"], meta["ymax"]),
    )

    # Resample the extracted line at the true x positions.
    y_pred = np.interp(truth["x"], df["x"], df["y"])
    err = y_pred - truth["y"]
    y_range = meta["ymax"] - meta["ymin"]
    rmse_pct = 100 * np.sqrt(np.mean(err**2)) / y_range
    mae_pct = 100 * np.mean(np.abs(err)) / y_range
    return mode, rmse_pct, mae_pct


def results_table(rows):
    """Format (chart, mode, rmse_pct, mae_pct) rows as a markdown table with mean and max rows."""
    rmse = [r[2] for r in rows]
    mae = [r[3] for r in rows]
    lines = ["| chart | mode | RMSE% | MAE% |", "|---|---|---:|---:|"]
    lines += [f"| {chart} | {mode} | {r:.2f} | {m:.2f} |" for chart, mode, r, m in rows]
    lines.append(f"| **mean** | | **{np.mean(rmse):.2f}** | **{np.mean(mae):.2f}** |")
    lines.append(f"| **max** | | **{np.max(rmse):.2f}** | **{np.max(mae):.2f}** |")
    return "\n".join(lines)


def main():
    """Evaluate every sample chart, print the table and save it to docs/."""
    charts = sorted(SAMPLES_DIR.glob("chart_[0-9][0-9].png"))
    rows = [(p.stem, *evaluate_chart(p)) for p in charts]
    table = results_table(rows)
    print(table)

    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text(
        "# Extraction results\n\n"
        f"Pipeline accuracy on the {len(rows)} synthetic charts in `samples/`. "
        "Errors are relative to the y-axis range (ymax - ymin). Axis limits come "
        "from the meta files, not from reading tick labels.\n\n"
        "Generated by `python -m src.evaluate`.\n\n" + table + "\n"
    )
    print(f"\nSaved to {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
